type Entry = { w: number; h: number; widths: number[]; avif: boolean };
const M = manifest as Record<string, Entry>;

export type Img = { src: string; srcSet: string; w: number; h: number; avif?: string };

/** Responsive source for a generated image. */
export function img(name: string): Img {
  const e = M[name];
  if (!e) throw new Error(`nd image missing: ${name}`);
  const set = (ext: string) => e.widths.map((w) => `/images/nd/${name}-${w}.${ext} ${w}w`).join(", ");
  const largest = e.widths[e.widths.length - 1];
  return { src: `/images/nd/${name}-${largest}.webp`, srcSet: set("webp"), w: e.w, h: e.h, avif: e.avif ? set("avif") : undefined };
}

